import fs from 'node:fs';
import path from 'node:path';
import { readConfig } from '../config/index.js';
import { LumenError, EXIT } from '../errors.js';
import { render, loadTemplateDir } from './template.js';
import { validateName, buildNameVariants } from './names.js';

/**
 * Resolves the destination directory for a generator kind from manifest.paths.
 * Never hardcodes src/...; uses manifest.paths only.
 *
 * @param {Record<string, string>} paths Resolved manifest paths object
 * @param {string} kind Generator target kind (e.g. 'features', 'components', etc.)
 * @param {string} [name] Name of resource (validated, not appended here)
 * @returns {string} Directory relative to project root
 * @throws {LumenError}
 */
export function resolveTarget(paths, kind, name) {
  if (name !== undefined) {
    validateName(name);
  }

  if (!paths || typeof paths !== 'object') {
    throw new LumenError('Invalid paths configuration in manifest.', {
      code: EXIT.CONFIG,
    });
  }

  const targetDir = paths[kind];
  if (!targetDir || typeof targetDir !== 'string') {
    const validKinds = Object.keys(paths).join(', ');
    throw new LumenError(
      `Unknown generator kind "${kind}". Valid kinds defined in manifest paths: ${validKinds}`,
      {
        code: EXIT.USER,
        hint: `Choose one of the configured path kinds: ${validKinds}`,
      }
    );
  }

  return targetDir;
}

/**
 * Validates that an absolute destination path is strictly contained within root.
 * Uses path.relative to reject '..' or absolute escapes.
 *
 * @param {string} root Absolute root directory
 * @param {string} targetPath Absolute target path
 * @throws {LumenError}
 */
export function assertPathContained(root, targetPath) {
  const resolvedRoot = path.resolve(root);
  const resolvedTarget = path.resolve(targetPath);

  const relative = path.relative(resolvedRoot, resolvedTarget);

  if (relative.startsWith('..') || path.isAbsolute(relative)) {
    throw new LumenError(
      `Security error: Target path "${targetPath}" resolves outside project root "${root}".`,
      {
        code: EXIT.USER,
        hint: 'Paths generated by templates and names must stay inside the project directory.',
      }
    );
  }
}

/**
 * Replace placeholders in path string (e.g. __name__, __Name__, __nameCamel__, etc.).
 *
 * @param {string} filePath
 * @param {Record<string, any>} vars
 * @returns {string}
 */
export function interpolatePath(filePath, vars) {
  let result = filePath;
  for (const [key, value] of Object.entries(vars)) {
    if (value !== undefined && value !== null) {
      result = result.replaceAll(`__${key}__`, String(value));
    }
  }
  return result;
}

/**
 * Computes the plan of files to create, skip, or overwrite.
 *
 * @param {object} params
 * @param {string} params.templateDir Absolute path to template folder
 * @param {Record<string, any>} params.vars Variables to interpolate
 * @param {string} params.targetDir Base directory relative to project root
 * @param {object} params.manifest Normalised manifest object
 * @param {string} params.root Absolute project root path
 * @returns {Array<{ path: string, relPath: string, contents: string, action: 'create' | 'skip' | 'overwrite' }>}
 */
export function planGenerator({ templateDir, vars, targetDir, manifest, root }) {
  if (!root) {
    throw new LumenError('Project root is required for planning generator.', {
      code: EXIT.INTERNAL,
    });
  }

  const language = manifest?.tooling?.language || 'ts';
  const templates = loadTemplateDir(templateDir, { language });

  const plan = [];

  for (const item of templates) {
    // Interpolate placeholders in relative path
    const interpolatedRel = interpolatePath(item.relPath, vars);

    // Compute relative destination path inside project root
    const destRelPath = path.posix.join(targetDir, interpolatedRel);
    const destFullPath = path.resolve(root, destRelPath);

    // Check strict containment
    assertPathContained(root, destFullPath);

    // Render contents
    const renderedContent = render(item.contents, vars);

    // Determine default action based on disk state
    const exists = fs.existsSync(destFullPath);
    const action = exists ? 'skip' : 'create';

    plan.push({
      path: destFullPath,
      relPath: destRelPath,
      contents: renderedContent,
      action,
    });
  }

  return plan;
}

/**
 * Applies a generator plan to disk.
 *
 * @param {Array<{ path: string, relPath: string, contents: string, action: string }>} plan
 * @param {{ dryRun?: boolean, force?: boolean }} [options={}]
 * @returns {{ plan: Array<any>, created: string[], skipped: string[], overwritten: string[] }}
 */
export function applyPlan(plan, { dryRun = false, force = false } = {}) {
  const created = [];
  const skipped = [];
  const overwritten = [];

  const finalPlan = plan.map((entry) => {
    const exists = fs.existsSync(entry.path);
    let action = entry.action;

    if (exists) {
      if (force) {
        action = 'overwrite';
      } else {
        action = 'skip';
      }
    } else {
      action = 'create';
    }

    if (!dryRun) {
      if (action === 'create' || action === 'overwrite') {
        fs.mkdirSync(path.dirname(entry.path), { recursive: true });
        fs.writeFileSync(entry.path, entry.contents, 'utf8');
      }
    }

    if (action === 'create') {
      created.push(entry.relPath || entry.path);
    } else if (action === 'overwrite') {
      overwritten.push(entry.relPath || entry.path);
    } else {
      skipped.push(entry.relPath || entry.path);
    }

    return {
      ...entry,
      action,
    };
  });

  return {
    plan: finalPlan,
    created,
    skipped,
    overwritten,
  };
}

/**
 * Synchronizes the .lumen agent context directory when manifest.agentDocs is enabled.
 * Emits .lumen/project.json, .lumen/architecture.json, and .lumen/conventions.md.
 * In architecture.json, populates `modules` array with discovered feature directories if paths.features is defined.
 * Reference: issue #31.
 *
 * @param {string} root Project root directory
 */
export async function syncAgentContext(root) {
  try {
    const { manifest, paths } = readConfig({ cwd: root });
    if (!manifest?.agentDocs) return;

    const { emitAgentContext } = await import('create-lumen/src/agent-context.js');
    await emitAgentContext(root, manifest);

    // Discover feature modules deterministically if paths.features is configured
    const lumenDir = path.join(root, '.lumen');
    const archFile = path.join(lumenDir, 'architecture.json');
    if (fs.existsSync(archFile)) {
      try {
        const arch = JSON.parse(fs.readFileSync(archFile, 'utf8'));
        let modules = [];
        if (paths?.features) {
          const featuresDir = path.resolve(root, paths.features);
          if (fs.existsSync(featuresDir)) {
            const entries = fs.readdirSync(featuresDir, { withFileTypes: true });
            modules = entries
              .filter((d) => d.isDirectory())
              .map((d) => d.name)
              .sort();
          }
        }
        arch.modules = modules;
        fs.writeFileSync(archFile, JSON.stringify(arch, null, 2) + '\n', 'utf8');
      } catch {
        // Ignore JSON parse error
      }
    }
  } catch {
    // Gracefully handle if config cannot be read
  }
}

/**
 * Orchestrates a generator invocation.
 * Reads config, validates inputs, builds plan, applies plan, and renders CLI output.
 *
 * @param {object} params
 * @param {string} params.kind Generator kind (e.g. 'features', 'components', etc.)
 * @param {string} params.name Resource name
 * @param {string} params.templateDir Absolute path to template directory
 * @param {object} [params.options={}] CLI options (cwd, json, dryRun, force)
 * @returns {Promise<object>} Generator execution result
 */
export async function runGenerator({ kind, name, templateDir, options = {} }) {
  const validatedName = validateName(name);
  const { manifest, paths, root } = readConfig({ cwd: options.cwd });

  // Resolve target directory from manifest.paths only
  const baseTargetDir = resolveTarget(paths, kind, validatedName);

  // Prepare standard template interpolation variables
  const vars = {
    ...buildNameVariants(validatedName),
    ...(options.vars || {}),
  };

  // Build execution plan
  const plan = planGenerator({
    templateDir,
    vars,
    targetDir: baseTargetDir,
    manifest,
    root,
  });

  // Apply plan
  const result = applyPlan(plan, {
    dryRun: Boolean(options.dryRun),
    force: Boolean(options.force),
  });

  // Call agent context sync if enabled (never during dry-run)
  if (manifest.agentDocs && !options.dryRun) {
    await syncAgentContext(root);
  }

  // CLI output formatting
  if (options.json) {
    const payload = {
      success: true,
      kind,
      name: validatedName,
      targetDir: baseTargetDir,
      dryRun: Boolean(options.dryRun),
      force: Boolean(options.force),
      created: result.created,
      skipped: result.skipped,
      overwritten: result.overwritten,
      plan: result.plan.map((p) => ({
        relPath: p.relPath,
        action: p.action,
      })),
    };
    process.stdout.write(`${JSON.stringify(payload, null, 2)}\n`);
  } else {
    if (options.dryRun) {
      process.stdout.write(`\n[DRY RUN] Generator plan for ${kind} "${validatedName}":\n`);
    } else {
      process.stdout.write(`\nGenerated ${kind} "${validatedName}":\n`);
    }

    for (const item of result.plan) {
      const tag =
        item.action === 'create'
          ? '+ CREATE'
          : item.action === 'overwrite'
          ? '! OVERWRITE'
          : '- SKIP';
      process.stdout.write(`  ${tag} ${item.relPath}\n`);
    }

    if (result.skipped.length > 0 && !options.force && !options.dryRun) {
      process.stdout.write(`\nNote: ${result.skipped.length} existing file(s) skipped. Use --force to overwrite.\n`);
    }
  }

  return {
    kind,
    name: validatedName,
    targetDir: baseTargetDir,
    ...result,
  };
}
